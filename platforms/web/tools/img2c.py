#!/usr/bin/env python3
"""binary → C++ 数组 (assets.img → assets_web.cc)。用法: img2c.py <in.bin> <out.cc>"""
import sys
src = open(sys.argv[1], "rb").read()
lines = [",".join(f"0x{b:02X}" for b in src[i:i+20]) for i in range(0, len(src), 20)]
body = ",\n".join(lines)
out = f"""/* auto-generated by build.sh (img2c.py) — do not edit */
#include <cstdint>
extern "C" const uint8_t tab5_web_assets_img[] = {{
{body}
}};
extern "C" const unsigned int tab5_web_assets_img_len = {len(src)};
"""
open(sys.argv[2], "w").write(out)
print(f"img2c: {len(src)} bytes -> {sys.argv[2]}")
