#!/usr/bin/env python3
"""每日一句 DB → 设备端数据头生成器 (2026-11-15, 去 OrangePi)

源 = hermes `hermes_mcp_server/data/daily_sentences.csv` 的本地拷贝
(app/apps/app_home/daily_sentences.csv, en/cn 两列, 用户提供)。
输出 = daily_sentences_data.h: 每行 `en\tcn\n` 的原始字符串 blob, 编进 app,
运行时按行偏移取句 (零解析依赖, 不占 res 分区)。

改了 CSV 后重跑:
    python3 app/apps/app_home/gen_daily_sentences.py
"""
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "daily_sentences.csv"
out = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "daily_sentences_data.h"

rows = []
with src.open(encoding="utf-8-sig", newline="") as f:
    for r in csv.reader(f):
        if len(r) >= 2 and r[0].strip() and r[1].strip():
            if rows or r[0].strip().lower() != "en":   # 跳过表头
                rows.append((r[0].strip(), r[1].strip()))

if not rows:
    sys.exit(f"no sentences in {src}")

blob = "".join(f"{en}\t{cn}\n" for en, cn in rows)
if ')DSENT"' in blob:
    sys.exit("delimiter collision: )DSENT\"")

with out.open("w", encoding="utf-8", newline="\n") as f:
    f.write("// AUTO-GENERATED by gen_daily_sentences.py — DO NOT EDIT.\n")
    f.write(f"// {len(rows)} 条, 源 = daily_sentences.csv (hermes 同款 DB)\n")
    f.write("#pragma once\n\n")
    f.write(f"static constexpr int kDailySentencesCount = {len(rows)};\n")
    f.write('static const char kDailySentencesBlob[] = R"DSENT(')
    f.write(blob)
    f.write(')DSENT";\n')

print(f"wrote {out}: {len(rows)} sentences, {len(blob.encode('utf-8'))} bytes")
